package dev.ivchenko.lwjwae.dialog;

/** The buttons of a message dialog, in the words and the order of the platform. */
public enum MessageButtons {
  /** One button that closes the dialog. */
  OK,

  /** Confirm or cancel: the answer is {@code true} for OK. */
  OK_CANCEL,

  /** Yes or no: the answer is {@code true} for yes. */
  YES_NO
}
